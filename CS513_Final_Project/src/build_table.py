import re

import numpy as np
import pandas as pd

import config
from src import common


def _slug(text):
    return re.sub(r"[^a-z0-9]+", "_", str(text).lower()).strip("_")


def _flag_columns(series, prefix):
    """Turn a multi-valued text column ('Brick; Terra Cotta') into 0-1 flags
    for the TOP_N_FLAGS most common values."""
    tokens = (series.fillna("").astype(str).str.upper()
              .str.split(r"\s*[,;|/]\s*", regex=True))
    tokens = tokens.apply(lambda items: {t.strip() for t in items if t.strip()})
    counts = pd.Series([t for items in tokens for t in items]).value_counts()
    flags = {}
    for value in counts.head(config.TOP_N_FLAGS).index:
        flags[f"{prefix}{_slug(value)}"] = tokens.apply(lambda items: int(value in items))
    return pd.DataFrame(flags, index=series.index)


def load_filings():
    c = config.FACADE_COLS
    raw = common.read_raw("facades")
    missing = common.missing_facade_columns(raw, config.FACADE_REQUIRED)
    if missing:
        raise SystemExit(
            "Required columns are missing from the facade file: "
            f"{missing}\nRun `python -m src.data_check`, then fix FACADE_COLS in config.py.")

    df = raw[common.is_initial_filing(raw[c["filing_type"]])].copy()
    df["rating"] = common.normalize_status(df[c["label_status"]])
    df = df[df["rating"].isin(common.RATINGS)].copy()
    df["bin"] = common.clean_id(df[c["bin"]])
    df = df[df["bin"].notna()].copy()
    df["cycle"] = df[c["cycle"]].astype(str).str.strip()
    df["cycle_num"] = pd.to_numeric(df["cycle"].str.extract(r"(\d+)")[0], errors="coerce")
    df["filing_date"] = pd.to_datetime(df[c["filing_date"]], errors="coerce")
    df["bbl"] = common.make_bbl(df[c["borough"]], df[c["block"]], df[c["lot"]])

    # One row per building per cycle: keep the earliest initial filing.
    df = (df.sort_values(["bin", "cycle_num", "filing_date"])
            .drop_duplicates(["bin", "cycle"], keep="first")
            .reset_index(drop=True))

    out = df[["bin", "bbl", "cycle", "cycle_num", "filing_date", "rating"]].copy()
    out["is_unsafe"] = (out["rating"] == "UNSAFE").astype(int)

    # ---- step 1 features: known from the filing itself, before the result ----
    out["f_cycle"] = "cycle_" + df["cycle"]
    out["f_borough"] = df[c["borough"]].fillna("UNKNOWN").astype(str).str.strip().str.upper()

    if c["prior_status"] in df.columns:
        prior = common.normalize_status(df[c["prior_status"]])
        prior = prior.where(prior.isin(common.RATINGS), "NO PRIOR RESULT")
    else:
        # Not in the file: take the same building's rating from its previous cycle.
        prior = out.groupby("bin")["rating"].shift(1).fillna("NO PRIOR RESULT")
    out["f_prior_status"] = prior.values

    for key, prefix in (("wall_type", "f_wall_"), ("wall_material", "f_mat_")):
        if c[key] in df.columns:
            out = pd.concat([out, _flag_columns(df[c[key]], prefix)], axis=1)
        else:
            print(f"  note: no '{c[key]}' column, so no {prefix}* flags were made")
    return out


def add_pluto(table):
    pluto = common.read_raw("pluto")
    pluto["bbl"] = common.clean_pluto_bbl(pluto["bbl"])
    pluto = pluto[pluto["bbl"].notna()].drop_duplicates("bbl")
    for col in ("numfloors", "yearbuilt", "yearalter1", "yearalter2", "bldgarea",
                "unitstotal", "latitude", "longitude"):
        pluto[col] = pd.to_numeric(pluto.get(col), errors="coerce")

    m = table.merge(pluto, on="bbl", how="left", indicator=True)
    matched = (m["_merge"] == "both")
    year = m["filing_date"].dt.year

    built = m["yearbuilt"].where(m["yearbuilt"] > 1700)
    table["p_age_at_filing"] = (year - built).where(lambda s: s >= 0).values
    table["p_numfloors"] = m["numfloors"].where(m["numfloors"] > 0).values
    table["p_bldgarea"] = m["bldgarea"].where(m["bldgarea"] > 0).values
    table["p_unitstotal"] = m["unitstotal"].values
    table["p_bldgclass"] = (m["bldgclass"].fillna("").astype(str).str[:1].str.upper()
                            .replace("", "UNKNOWN").values)
    for col in ("landmark", "histdist"):
        has_value = m[col].fillna("").astype(str).str.strip().ne("") if col in m else False
        table[f"p_{col}"] = np.where(matched, np.asarray(has_value, dtype=int), np.nan)

    # PLUTO describes the building TODAY. Only count an alteration that happened
    # before the filing year, otherwise the model would see the future.
    alter = pd.concat([m[a].where((m[a] > 1700) & (m[a] < year))
                       for a in ("yearalter1", "yearalter2")], axis=1).max(axis=1)
    table["p_years_since_alter"] = (year - alter).values
    table["p_ever_altered"] = np.where(matched, alter.notna().astype(int), np.nan)

    table["map_lat"] = m["latitude"].values
    table["map_lon"] = m["longitude"].values
    table["pluto_matched"] = matched.astype(int).values
    return table


def add_violations(table):
    ecb = common.read_raw("ecb")
    ecb["bin"] = common.clean_id(ecb["bin"])
    ecb = ecb[ecb["bin"].isin(set(table["bin"]))].copy()
    ecb["issue_dt"] = common.parse_ecb_date(ecb["issue_date"])
    ecb = ecb[ecb["issue_dt"].notna()]
    ecb["class1"] = ecb["severity"].fillna("").str.upper().str.contains(r"CLASS\s*-?\s*1|HAZ").astype(int)
    ecb["construction"] = ecb["violation_type"].fillna("").str.upper().str.contains("CONSTRUCTION").astype(int)

    table = table.reset_index(drop=True)
    table["row_id"] = table.index
    pairs = table[["row_id", "bin", "filing_date"]].merge(
        ecb[["bin", "issue_dt", "class1", "construction"]], on="bin", how="inner")

    # LEAKAGE RULE: only violations issued strictly BEFORE the filing date.
    # This also removes any violation written because of this filing's result.
    # We do not use "open violations": the open/closed status in the file is
    # today's status, which nobody knew on the inspection date.
    pairs = pairs[pairs["issue_dt"] < pairs["filing_date"]]
    pairs["years_before"] = (pairs["filing_date"] - pairs["issue_dt"]).dt.days / 365.25

    agg = pairs.groupby("row_id").agg(
        v_total=("class1", "size"),
        v_class1=("class1", "sum"),
        v_construction=("construction", "sum"),
        v_last5yrs=("years_before", lambda s: int((s <= 5).sum())),
        v_years_since_last=("years_before", "min"),
    )
    table = table.join(agg, on="row_id")
    counts = ["v_total", "v_class1", "v_construction", "v_last5yrs"]
    has_date = table["filing_date"].notna()
    table.loc[has_date, counts] = table.loc[has_date, counts].fillna(0)
    table["v_any"] = np.where(has_date, (table["v_total"] > 0).astype(int), np.nan)
    return table.drop(columns="row_id")


def main():
    print("Reading facade filings ...")
    table = load_filings()
    print("Adding PLUTO ...")
    table = add_pluto(table)
    print("Adding violation history ...")
    table = add_violations(table)

    config.PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    table.to_csv(config.TABLE_PATH, index=False)

    n = len(table)
    print(f"\nSaved {config.TABLE_PATH}")
    print(f"Rows (initial filings): {n:,}    Buildings: {table['bin'].nunique():,}")
    print(f"Unsafe share: {table['is_unsafe'].mean():.1%}")
    print(f"Matched to PLUTO: {table['pluto_matched'].mean():.1%}")
    print(f"With at least one earlier violation: {(table['v_total'] > 0).mean():.1%}")
    for prefix, label in (("f_", "filing"), ("p_", "PLUTO"), ("v_", "violation")):
        cols = [col for col in table.columns if col.startswith(prefix)]
        print(f"  {label} features ({len(cols)}): {', '.join(cols)}")


if __name__ == "__main__":
    main()
